/**
 * Builds public/medmatch/index.html from the standalone MedMatch/MedMatch.html.
 *
 * The standalone file ships @babel/standalone (2.4 MB of the 2.8 MB total) and
 * transpiles the game's JSX in the browser on every load — fine for a file you
 * double-click offline, far too heavy for a phone opening the site. This script
 * keeps the embedded React/ReactDOM and the storage polyfill, transpiles the
 * JSX ahead of time with esbuild, and drops Babel entirely.
 *
 * The output is committed, like the crossword and Doctordle pages, so this only
 * needs re-running after editing MedMatch/MedMatch.html:  npm run build:medmatch
 * (esbuild comes along with Vite — no extra dependency.)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'MedMatch/MedMatch.html'), 'utf8');

/** Pull out the content of a <script> block identified by a marker inside it. */
function scriptContaining(marker) {
  const at = src.indexOf(marker);
  if (at === -1) throw new Error(`marker not found: ${marker}`);
  const open = src.lastIndexOf('<script', at);
  const start = src.indexOf('>', open) + 1;
  const end = src.indexOf('</script>', start);
  if (open === -1 || end === -1) throw new Error(`unterminated script for: ${marker}`);
  return src.slice(start, end);
}

const react = scriptContaining('/* React 18.3.1');
const reactDom = scriptContaining('/* ReactDOM 18.3.1');
const storage = scriptContaining('if (window.storage) return;');
const game = scriptContaining('MEDMATCH — MLAConditions minigame');

const { code } = transformSync(game, {
  loader: 'jsx',
  jsx: 'transform', // classic runtime — React is a global here, not an import
  target: 'es2019',
  format: 'iife',
  minify: true, // the bank alone is ~150 KB of the source; this roughly halves it
  legalComments: 'none',
});

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<title>MedMatch — MLAConditions</title>
<style>
  html, body { margin: 0; padding: 0; background: #0b1020; min-height: 100%; }
  body { -webkit-text-size-adjust: 100%; overscroll-behavior: none; }
  #root { min-height: 100%; }
  #boot {
    min-height: 60vh; display: flex; align-items: center; justify-content: center;
    color: #98a1c4; font-family: ui-sans-serif, system-ui, -apple-system, sans-serif; font-size: 14px;
    text-align: center; padding: 24px; line-height: 1.6;
  }
</style>
</head>
<body>
<div id="root"><div id="boot">Loading MedMatch…</div></div>

<!-- Generated by scripts/build-medmatch.mjs from MedMatch/MedMatch.html.
     Edit that file, not this one, then re-run the script. -->

<script>
/* React 18.3.1 — MIT License — https://github.com/facebook/react */
${react.trim()}
</script>
<script>
/* ReactDOM 18.3.1 — MIT License — https://github.com/facebook/react */
${reactDom.trim()}
</script>
<script>
window.addEventListener("error", function (e) {
  var boot = document.getElementById("boot");
  if (boot) {
    boot.innerHTML =
      "Something went wrong loading MedMatch.<br>" +
      "<span style='font-size:11px;opacity:.7'>" + (e && e.message ? e.message : "") + "</span>";
  }
});
</script>
<script>
${storage.trim()}
</script>
<script>
${code.trim()}
</script>
</body>
</html>
`;

const out = resolve(root, 'public/medmatch/index.html');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(`wrote ${out} — ${(html.length / 1024).toFixed(0)} KB (source was ${(src.length / 1024).toFixed(0)} KB)`);
